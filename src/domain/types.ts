import type { PortfolioData } from './portfolioModel'

/** Envelope types supported in v1 */
export type EnvelopeType =
  | 'PEA'
  | 'PEA_PME'
  | 'CTO'
  | 'PEA_SAXO'
  | 'PEA_PME_SAXO'
  | 'CTO_SAXO'

export type OperationType =
  | 'ACHAT'
  | 'VENTE'
  | 'SCRIPT'
  | 'RACHAT'
  | 'DIVIDENDE'
  | 'DETACHEMENT'
  | 'ACTIONS_GRATUITES'
  | 'AUGMENTATION_CAPITAL'
  | 'VERSEMENT'
  | 'RETRAIT'
  | 'FRAIS'
  | 'TAXE'
  | 'OST_OTHER'
  | 'OST_SPLIT'
  | 'OST_FUSION'
  | 'POSITION_SEED'
  | 'UNKNOWN'

export interface ManualPrice {
  date: string // YYYY-MM-DD
  price: number
}

export interface Support {
  /** Primary key for engines: real ISIN, LOCAL:…, or ID:n */
  isin: string
  /** Portfolio Support.uniqueID when persisted in schema v2+ */
  uniqueID?: number
  name: string
  yahooTicker?: string
  googleTicker?: string
  boursoramaTicker?: string
  manualPrices: ManualPrice[]
  /** Fallback constant price when no Yahoo / manual history */
  staticPrice?: number
  /**
   * Quote / instrument currency (e.g. USD). EUR or unset = euro book.
   * Yahoo/Morningstar closes are in this currency; chart display follows it.
   */
  quoteCurrency?: string
  /**
   * Options / turbos / warrants: never pull Yahoo/Morningstar (underlying
   * prices × contract size explode the valuation). Use trade-seeded manuals.
   */
  tradeQuotesOnly?: boolean
}

export interface Operation {
  id: string
  fingerprint: string
  envelope: EnvelopeType
  date: string // YYYY-MM-DD
  type: OperationType
  isin?: string
  name?: string
  quantity?: number
  price?: number
  grossAmount?: number
  fees?: number
  netAmount?: number
  /** Account / booked currency (usually EUR). */
  currency?: string
  /**
   * Instrument quote currency when different from account (e.g. USD).
   * Empty/undefined when the support trades in EUR.
   */
  instrumentCurrency?: string
  /**
   * Signed notional in instrument currency (qty × price).
   * Left undefined when instrument currency is EUR / same as account.
   */
  instrumentAmount?: number
  /**
   * Account currency per 1 unit of instrument currency (Saxo « Taux de change »).
   * EUR = instrumentAmount × fxRate (approx., fees aside).
   */
  fxRate?: number
  /** Fortuneo « Place » column (e.g. Euronext Paris) — listing hint for resolution */
  place?: string
  label: string
  /** True when generated by backward reconstruction */
  synthetic?: boolean
}

export interface VirtualOpeningPosition {
  isin: string
  name: string
  quantity: number
}

export interface VirtualOpening {
  envelope: EnvelopeType
  date: string
  /** Opening cash for holdings replay (titres-only: usually 0). */
  cash: number
  /**
   * Idle cash today (from positions / import). Shown on the last chart day
   * only — not projected backward as a cumulative pocket.
   */
  reportedCash?: number
  positions: VirtualOpeningPosition[]
  computedAt: string
}

export interface EnvelopeMeta {
  type: EnvelopeType
  label: string
  createdAt: string
  updatedAt: string
}

export interface QuoteBar {
  date: string // YYYY-MM-DD
  close: number
}

export interface QuoteSeries {
  ticker: string
  bars: QuoteBar[]
  updatedAt: string
}

export interface UiPrefs {
  theme?: 'light' | 'dark'
  chartBase100?: boolean
  defaultPeriod?: ChartPeriod
}

export type ChartPeriod = '1M' | '3M' | '1Y' | '2Y'

export const SCHEMA_VERSION = 2
export const APP_NAME = 'VisualiseurFortuneo'

/** Schema v2 export = Portfolio.toJSON() (+ optional quotes). v1 still importable. */
export interface ExportBundle {
  meta: {
    app: typeof APP_NAME
    schemaVersion: number
    date: string
  }
  /** v2 primary payload */
  portfolio?: PortfolioData
  /** v1 legacy fields (import migrates to portfolio) */
  envelopes?: EnvelopeMeta[]
  operations?: Operation[]
  supports?: Support[]
  virtualOpenings?: VirtualOpening[]
  quoteCache?: QuoteSeries[]
  uiPrefs?: UiPrefs
}

/** Open positions snapshot from Fortuneo XLS/CSV */
export interface ParsedPosition {
  isin: string
  name: string
  quantity: number
  price?: number
  pru?: number
  valuation?: number
  currency?: string
}

export interface ImportReport {
  envelope: EnvelopeType
  added: number
  skippedDuplicates: number
  supportsCreated: number
  virtualOpening: VirtualOpening | null
  warnings: string[]
}
